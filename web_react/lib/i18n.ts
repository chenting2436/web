const zhToEn = new Map<string, string>(translationPairs);
const enToZh = new Map<string, string>(translationPairs.map(([zh, en]) => [en, zh]));

const byLength = (entries: IterableIterator<[string, string]>) =>
  [...entries].sort(([left], [right]) => right.length - left.length);

const zhPhrases = byLength(zhToEn.entries());
const enPhrases = byLength(enToZh.entries());

export function translateText(value: string, locale: Locale): string {
  const normalized = value.trim();
  if (!normalized) return value;
  const exact = locale === 'en' ? zhToEn.get(normalized) : enToZh.get(normalized);
  if (exact) return value.replace(normalized, exact);

  const phrases = locale === 'en' ? zhPhrases : enPhrases;
  let translated = value;
  for (const [source, target] of phrases) {
    if (source.length < 2 || !translated.includes(source)) continue;
    translated = translated.replaceAll(source, target);
  }
  return translated;
}
